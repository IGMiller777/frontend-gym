export type PerfDict = typeof ru
export const perfStrings: Record<Locale, PerfDict> = { ru, en }

/** Incident simulator strings in the current interface language. */
export function usePerfT(): PerfDict {
  return perfStrings[useProgress((s) => s.locale)]
}
