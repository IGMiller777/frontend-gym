/** Russian plural forms: 1 час, 2 часа, 5 часов. */
function plural(n: number, one: string, few: string, many: string): string {
  const rule = new Intl.PluralRules('ru').select(n)
  return rule === 'one' ? one : rule === 'few' ? few : many
}

